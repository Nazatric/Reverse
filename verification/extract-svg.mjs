/* ------------------------------------------------------------- JSX-subset reader */

const VOID = new Set(["stop", "path", "circle", "ellipse", "rect", "line", "polygon", "polyline", "use", "image"]);
const DRAWABLE = new Set(["path", "circle", "ellipse", "rect", "line", "polygon", "polyline", "text"]);

/** Index of the `}` matching the `{` at `i`, ignoring braces inside quotes/template literals. */
function matchBrace(src, i) {
  let depth = 0;
  let quote = null;
  for (let j = i; j < src.length; j++) {
    const c = src[j];
    if (quote) {
      if (c === "\\") j++;
      else if (c === quote) quote = null;
      continue;
    }
    if (c === '"' || c === "'" || c === "`") quote = c;
    else if (c === "{") depth++;
    else if (c === "}") {
      depth--;
      if (depth === 0) return j;
    }
  }
  throw new Error("unbalanced { in JSX");
}

/** Index of the `>` that closes the tag starting at `from`. */
function findTagEnd(src, from) {
  let quote = null;
  let depth = 0;
  for (let j = from + 1; j < src.length; j++) {
    const c = src[j];
    if (quote) {
      if (c === "\\") j++;
      else if (c === quote) quote = null;
      continue;
    }
    if (c === '"' || c === "'" || c === "`") quote = c;
    else if (c === "{") depth++;
    else if (c === "}") depth--;
    else if (c === ">" && depth === 0) return j;
  }
  throw new Error(`unterminated tag near: ${src.slice(from, from + 60)}`);
}

const tagName = (tagSrc) => (tagSrc.match(/^[A-Za-z0-9_.>-]+/) || [""])[0];

/** `d="M0 0" fill={ink} {...S}` → { d: {literal}, fill: {expr}, "…S": {spread: "S"} } */
function parseAttrs(tagSrc) {
  const attrs = {};
  let i = 0;
  while (i < tagSrc.length) {
    while (i < tagSrc.length && /\s/.test(tagSrc[i])) i++;
    if (i >= tagSrc.length) break;
    const start = i;
    while (i < tagSrc.length && /[A-Za-z0-9_:.\-$]/.test(tagSrc[i])) i++;
    const name = tagSrc.slice(start, i);
    if (!name) { i++; continue; }
    if (name.startsWith("...")) {
      attrs[name] = { spread: name.slice(3) };
      continue;
    }
    if (tagSrc[i] !== "=") {
      attrs[name] = { literal: "true" };
      continue;
    }
    i++;
    if (tagSrc[i] === '"' || tagSrc[i] === "'") {
      const q = tagSrc[i];
      const s = ++i;
      while (i < tagSrc.length && tagSrc[i] !== q) i++;
      attrs[name] = { literal: tagSrc.slice(s, i) };
      i++;
    } else if (tagSrc[i] === "{") {
      const end = matchBrace(tagSrc, i);
      attrs[name] = { expr: tagSrc.slice(i + 1, end) };
      i = end + 1;
    } else {
      const s = i;
      while (i < tagSrc.length && !/[\s>]/.test(tagSrc[i])) i++;
      attrs[name] = { literal: tagSrc.slice(s, i) };
    }
  }
  return attrs;
}

/** Text of the element closed by `</name>`, plus the index just past that close tag. */
function sliceUntilClose(src, from, name) {
  let i = from;
  let depth = 1;
  while (i < src.length) {
    const c = src[i];
    if (c === "{") {
      i = matchBrace(src, i) + 1;
      continue;
    }
    if (c === "<") {
      if (src.startsWith("<!--", i)) {
        const e = src.indexOf("-->", i);
        i = e < 0 ? src.length : e + 3;
        continue;
      }
      if (src.startsWith("</", i)) {
        const end = src.indexOf(">", i);
        if (src.slice(i + 2, end).trim() === name) {
          depth--;
          if (depth === 0) return { text: src.slice(from, i), end: end + 1 };
        }
        i = end + 1;
        continue;
      }
      const end = findTagEnd(src, i);
      const tagSrc = src.slice(i + 1, end);
      if (tagName(tagSrc) === name && !tagSrc.trimEnd().endsWith("/")) depth++;
      i = end + 1;
      continue;
    }
    i++;
  }
  throw new Error(`missing </${name}>`);
}

/**
 * Parse a JSX region into a node tree. Expression blocks (`{cond && (…)}`, `{list.map(…)}`,
 * `{value}`) are kept as `expr` nodes; any JSX inside one is parsed too, because the sources use
 * those blocks to hold real drawing content.
 */
function parseChildren(src) {
  const nodes = [];
  let i = 0;
  while (i < src.length) {
    const c = src[i];
    if (c === "<") {
      if (src.startsWith("<!--", i)) {
        const e = src.indexOf("-->", i);
        i = e < 0 ? src.length : e + 3;
        continue;
      }
      if (src.startsWith("</", i)) break;
      const end = findTagEnd(src, i);
      const tagSrc = src.slice(i + 1, end);
      const name = tagName(tagSrc);
      const selfClosing = tagSrc.trimEnd().endsWith("/") || VOID.has(name);
      const attrSrc = tagSrc.slice(name.length).replace(/\/\s*$/, "");
      const node = { kind: "el", tag: name, attrs: parseAttrs(attrSrc), children: [] };
      i = end + 1;
      if (!selfClosing) {
        const inner = sliceUntilClose(src, i, name);
        node.children = parseChildren(inner.text);
        i = inner.end;
      }
      nodes.push(node);
      continue;
    }
    if (c === "{") {
      if (src.startsWith("{/*", i)) {
        const e = src.indexOf("*/}", i);
        i = e < 0 ? src.length : e + 3;
        continue;
      }
      const end = matchBrace(src, i);
      const code = src.slice(i + 1, end);
      const node = { kind: "expr", code, children: [] };
      const jsx = code.search(/<[A-Za-z>]/);
      if (jsx >= 0) node.children = parseChildren(code.slice(jsx));
      nodes.push(node);
      i = end + 1;
      continue;
    }
    let j = i;
    while (j < src.length && src[j] !== "<" && src[j] !== "{") j++;
    const text = src.slice(i, j);
    if (text.trim()) nodes.push({ kind: "text", value: text.trim() });
    i = j;
  }
  return nodes;
}

/** The first `<svg …>` in a region, as { root, children } — or null. */
function parseSvg(region) {
  const at = region.indexOf("<svg");
  if (at < 0) return null;
  const end = findTagEnd(region, at);
  const tagSrc = region.slice(at + 1, end);
  const inner = sliceUntilClose(region, end + 1, "svg");
  return {
    root: { tag: "svg", attrs: parseAttrs(tagSrc.slice(3)), children: [] },
    children: parseChildren(inner.text),
  };
}

/* ------------------------------------------------------------- component bodies */

/** Bodies of `[export] function Name(…) { … }`. */
function functionComponents(source) {
  const out = [];
  const re = /(?:export\s+)?function\s+([A-Za-z0-9_]+)\s*\([^)]*\)\s*\{/g;
  let m;
  while ((m = re.exec(source))) {
    const open = re.lastIndex - 1;
    const end = matchBrace(source, open);
    out.push({ name: m[1], body: source.slice(open + 1, end) });
  }
  return out;
}

/** Bodies of `const Name = (…) => ( … );` / `=> { … }`. */
function arrowComponents(source) {
  const out = [];
  const re = /const\s+([A-Z][A-Za-z0-9_]*)\s*(?::[^=]+)?=\s*\(([^)]*)\)\s*=>\s*/g;
  let m;
  while ((m = re.exec(source))) {
    let i = re.lastIndex;
    let body;
    if (source[i] === "{") {
      const end = matchBrace(source, i);
      body = source.slice(i + 1, end);
    } else {
      // expression body: read to the matching `);` at depth 0
      let depth = 0;
      let quote = null;
      let j = i;
      for (; j < source.length; j++) {
        const c = source[j];
        if (quote) {
          if (c === "\\") j++;
          else if (c === quote) quote = null;
          continue;
        }
        if (c === '"' || c === "'" || c === "`") quote = c;
        else if ("([{".includes(c)) depth++;
        else if (")]}".includes(c)) {
          depth--;
          if (depth === 0) break;
        }
      }
      body = source.slice(i, j);
    }
    out.push({ name: m[1], body });
  }
  return out;
}

/* ------------------------------------------------------------- dynamic values */

/**
 * Values the sources compute instead of writing literally. Each resolver throws rather than
 * returning a guess: a missing curve is worse than a loud failure.
 */
function variantTokens(body) {
  const tokens = {};
  const re = /const\s+([A-Za-z_$][\w$]*)\s*=\s*yellow\s*\?\s*"([^"]+)"\s*:\s*"([^"]+)"/g;
  let m;
  while ((m = re.exec(body))) tokens[m[1]] = { yellow: m[2], mono: m[3] };
  return tokens;
}

function variantStops(body) {
  const m = body.match(/const\s+stops\s*=\s*yellow\s*\?\s*(\[\[[\s\S]*?\]\])\s*:\s*(\[\[[\s\S]*?\]\])/);
  if (!m) return null;
  return { yellow: JSON.parse(m[1]), mono: JSON.parse(m[2]) };
}

/**
 * ConfigGlyph builds its two gear paths with a local `gear(…)` helper. Running the real function
 * is the only way to get the same `d` the browser gets, so the local arrow functions of the
 * component are lifted into an evaluator. Expressions are restricted to a safe charset.
 */
function localEvaluator(body) {
  const fns = [];
  const re = /const\s+([A-Za-z_$][\w$]*)\s*=\s*\(([^)]*)\)\s*=>\s*\{/g;
  let m;
  while ((m = re.exec(body))) {
    const end = matchBrace(body, re.lastIndex - 1);
    fns.push(body.slice(m.index, end + 1));
    re.lastIndex = end;
  }
  if (!fns.length) return null;
  // The sources are TypeScript, so strip the type annotations with the same esbuild the web build
  // uses before evaluating — hand-rolled type stripping would silently diverge on the first
  // non-trivial signature.
  const prelude = execFileSync(path.join(ROOT, "node_modules/esbuild/bin/esbuild"), ["--loader=ts"], {
    input: fns.join("\n"),
    encoding: "utf8",
  });
  return (expr) => {
    if (!/^[\w$.\s,()*/+-]*$/.test(expr)) throw new Error(`refusing to evaluate {${expr}}`);
    return new Function(`${prelude}\nreturn (${expr});`)();
  };
}

/* ------------------------------------------------------------- attribute handling */

const camel = (k) => k.replace(/-([a-z])/g, (_, c) => c.toUpperCase());

/** Presentation attributes that SVG inherits down the tree. */
const INHERITED = [
  "fill", "fillOpacity", "fillRule", "stroke", "strokeWidth", "strokeOpacity",
  "strokeLinecap", "strokeLinejoin", "clipPath",
];
/** Everything SvgElement can carry (camelCased). */
const KEPT = [
  "d", "cx", "cy", "r", "rx", "ry", "x", "y", "x1", "y1", "x2", "y2", "width", "height", "points",
  ...INHERITED, "opacity", "transform", "className", "textAnchor", "fontSize", "fontFamily",
];

/** Attributes that exist for the DOM/a11y and have no meaning to a Canvas renderer. */
const IGNORED = new Set([
  "ariaHidden", "focusable", "key", "decoding", "draggable", "alt", "xmlns", "preserveAspectRatio",
  "version", "role", "tabIndex", "loading", "crossOrigin",
]);

function resolveValue(spec, ctx, where) {
  if (spec.literal !== undefined) return spec.literal.trim();
  const e = (spec.expr ?? "").trim();
  if (/^"([^"]*)"$/.test(e) || /^'([^']*)'$/.test(e)) return e.slice(1, -1);
  if (e.startsWith("`") && e.endsWith("`")) {
    const body = e.slice(1, -1);
    if (!body.includes("${")) return body;
    // React's useId() prefix: `${id}f` → the group-namespaced gradient/clip id.
    const resolved = body.replace(/\$\{\s*id\s*\}/g, `${ctx.ns}.`);
    if (resolved.includes("${")) throw new Error(`${where}: cannot resolve template {${e}}`);
    return resolved;
  }
  if (/^-?[\d.]+$/.test(e)) return e;
  if (/^[A-Za-z_$][\w$]*$/.test(e)) {
    if (ctx.tokens[e]) return `token:${e}`;
    throw new Error(`${where}: cannot resolve identifier {${e}}`);
  }
  if (/^[A-Za-z_$][\w$]*\(/.test(e) && ctx.evaluate) {
    const value = ctx.evaluate(e);
    if (value !== undefined && value !== null) return String(value);
  }
  if (/^cx\(/.test(e)) {
    const parts = [...e.matchAll(/"([^"]*)"/g)].map((m) => m[1]);
    if (parts.length) return parts.join(" ");
  }
  throw new Error(`${where}: cannot resolve attribute value {${e}}`);
}

/**
 * Resolved attribute map. `only` restricts to SvgElement's fields; structural elements (the <svg>
 * root, gradients, clip paths) resolve everything they carry. Non-presentation attributes that the
 * renderer has no use for (aria-*, focusable, key, decoding…) are ignored.
 */
function resolveAttrs(node, ctx, where, only = null) {
  const out = {};
  for (const [rawName, spec] of Object.entries(node.attrs)) {
    if (spec.spread) {
      for (const [k, v] of Object.entries(ctx.spreads[spec.spread] || {})) out[camel(k)] = v;
      continue;
    }
    const name = camel(rawName);
    if (IGNORED.has(name)) continue;
    if (only && !only.includes(name)) continue;
    try {
      out[name] = resolveValue(spec, ctx, `${where} ${rawName}`);
    } catch (err) {
      // `className={className}` on every root <svg>: the class comes from the call site, so the
      // group simply carries no static one. Every other unresolved value stays an error.
      if (name === "className" && /^[A-Za-z_$][\w$]*$/.test((spec.expr ?? "").trim())) continue;
      throw err;
    }
  }
  return out;
}

/* ------------------------------------------------------------- defs */

/** `44%` → 0.44, `0.44` → 0.44 (SVG gradientUnits defaults to objectBoundingBox). */
function gradientCoord(v) {
  if (v === undefined || v === null) return null;
  const s = String(v).trim();
  return s.endsWith("%") ? Number(s.slice(0, -1)) / 100 : Number(s);
}

function stopElements(node, ctx, where) {
  const stops = [];
  let variantStopsFound = null;
  for (const child of node.children) {
    if (child.kind === "expr") {
      if (/stops\s*\.\s*map/.test(child.code)) {
        variantStopsFound = ctx.variantStops;
        continue;
      }
      throw new Error(`${where}: unexpected expression inside <${node.tag}>: {${child.code.slice(0, 40)}}`);
    }
    if (child.kind !== "el" || child.tag !== "stop") continue;
    const a = resolveAttrs(child, ctx, `${where} stop`);
    stops.push({
      offset: Number(a.offset ?? 0),
      color: a.stopColor ?? a.color ?? "#000",
      opacity: a.stopOpacity === undefined ? 1 : Number(a.stopOpacity),
    });
  }
  return { stops, variantStopsFound };
}

function parseDefs(nodes, ctx) {
  const gradients = [];
  const clips = [];
  const walk = (list) => {
    for (const n of list) {
      if (n.kind !== "el") continue;
      if (n.tag === "linearGradient" || n.tag === "radialGradient") {
        const a = resolveAttrs(n, ctx, `defs ${n.tag}`);
        const id = a.id ?? throw_(`${n.tag} without id`);
        const { stops, variantStopsFound } = stopElements(n, ctx, `defs ${n.tag}`);
        const geom = {
          x1: gradientCoord(a.x1), y1: gradientCoord(a.y1),
          x2: gradientCoord(a.x2), y2: gradientCoord(a.y2),
          cx: gradientCoord(a.cx), cy: gradientCoord(a.cy), r: gradientCoord(a.r),
        };
        if (variantStopsFound) {
          for (const variant of ["yellow", "mono"]) {
            gradients.push({
              id, kind: n.tag === "radialGradient" ? "radial" : "linear", ...geom, variant,
              stops: variantStopsFound[variant].map(([o, c]) => ({ offset: Number(o), color: c, opacity: 1 })),
            });
          }
        } else {
          if (stops.length < 2) throw_(`gradient ${id} has ${stops.length} stops`);
          gradients.push({ id, kind: n.tag === "radialGradient" ? "radial" : "linear", ...geom, stops });
        }
      } else if (n.tag === "clipPath") {
        const a = resolveAttrs(n, ctx, "defs clipPath");
        const id = a.id ?? throw_("clipPath without id");
        const elements = [];
        flatten(n.children, { ...ctx, inClip: true }, elements);
        clips.push({ id, elements });
      } else {
        walk(n.children);
      }
    }
  };
  walk(nodes);
  return { gradients, clips };
}

const throw_ = (msg) => {
  throw new Error(msg);
};

/* ------------------------------------------------------------- flattening */

/**
 * Walk the drawing tree, emitting one flat record per primitive with the presentation attributes
 * the browser would have resolved for it: ancestor paint inherited, transforms composed in order,
 * the nearest clip path remembered, and the class names accumulated (they drive the CSS
 * animations the native layer reproduces).
 */
function flatten(nodes, ctx, out) {
  for (const n of nodes) {
    if (n.kind === "text") {
      if (ctx.textTarget) ctx.textTarget.text = n.value;
      continue;
    }
    if (n.kind === "expr") {
      flatten(n.children, ctx, out);
      continue;
    }
    if (n.tag === "defs") continue;

    const own = resolveAttrs(n, ctx, `<${n.tag}>`, n.tag === "g" || n.tag === "svg" ? null : KEPT);
    const where = `<${n.tag}>`;

    if (n.tag === "g" || n.tag === "svg") {
      const child = {
        ...ctx,
        paint: { ...ctx.paint },
        transform: [...ctx.transform],
        classes: [...ctx.classes],
      };
      for (const k of INHERITED) if (own[k] !== undefined) child.paint[k] = own[k];
      if (own.transform) child.transform.push(own.transform);
      if (own.className) child.classes.push(own.className);
      if (own.clipPath) child.clipPath = own.clipPath;
      flatten(n.children, child, out);
      continue;
    }

    if (!DRAWABLE.has(n.tag)) {
      flatten(n.children, ctx, out);
      continue;
    }

    const el = { kind: n.tag };
    for (const k of KEPT) {
      if (own[k] !== undefined) el[k] = own[k];
      else if (INHERITED.includes(k) && ctx.paint[k] !== undefined) el[k] = ctx.paint[k];
    }
    const transform = [...ctx.transform, ...(own.transform ? [own.transform] : [])];
    if (transform.length) el.transform = transform.join(" ");
    const classes = [...ctx.classes, ...(own.className ? [own.className] : [])];
    if (classes.length) el.className = classes.join(" ");
    const clip = own.clipPath ?? ctx.clipPath;
    if (clip) el.clipPath = clip;
    if (n.tag === "text") {
      el.text = "";
      for (const child of n.children) if (child.kind === "expr") el.text = `{${child.code.trim()}}`;
      else if (child.kind === "text") el.text = child.value;
    }
    out.push(el);
    flatten(n.children, ctx, out);
  }
}

