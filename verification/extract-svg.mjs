/**
 * Mechanical SVG extraction — the visual half of the parity story.
 *
 * The native app must draw the *same* geometry the web app draws, not a hand-redrawn
 * approximation. Rather than retyping path data (where drift creeps in), this script parses the web
 * sources and emits everything the renderer needs — geometry, inherited paint, composed transforms,
 * gradients, clip paths and the variant-dependent paints — into a generated Kotlin file the Compose
 * layer consumes.
 *
 * Sources parsed (every file in src/ that contains an <svg>):
 *   src/components/ui/Icons.tsx      — the 34 icons in the PATHS map (+ { ...S } spread defaults)
 *   src/components/hub/Glyphs.tsx    — the seven hub-node glyphs (ConfigGlyph's gear paths are
 *                                      generated by a function in that file, so it is evaluated)
 *   src/components/hub/Wireframe.tsx — the 24 backdrop curves + rings
 *   src/components/hub/TopBar.tsx    — the up-arrow logo (with its gradient)
 *   src/components/hub/Chains.tsx    — the chain tile, an SVG data-URI with three gradients
 *   src/components/ui/Art.tsx        — the disc fallback artwork
 *   src/components/MascotFace.tsx    — the mascot: 4 gradients, 2 clip paths, yellow/mono variants
 *
 * What "parsed" means here: a small JSX-subset reader (tags, attributes, string/`{expr}` values,
 * fragments, comments, nesting) plus resolvers for the three dynamic patterns these files actually
 * use — `url(#${id}x)` from React's useId(), variant ternaries (`const ink = yellow ? A : B`,
 * `const stops = yellow ? […] : […]`) and locally-defined pure generator functions. Anything else
 * throws, so the generated file can never silently lose a curve.
 *
 * Output: android/app/src/main/kotlin/com/thegadget/app/ui/SvgPaths.kt  (generated, committed)
 *
 * Usage: node verification/extract-svg.mjs [--check]
 *        --check  fail (exit 1) if the generated file differs from what is on disk
 */
