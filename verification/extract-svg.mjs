/** Icons.tsx: a `PATHS` record of `name: <path … />` entries with a `{ ...S }` spread. */
function iconGroups() {
  const source = read("src/components/ui/Icons.tsx");
  const spreadSrc = source.match(/const\s+S\s*=\s*\{([^}]*)\}/);
  const spreads = { S: {} };
  if (spreadSrc) {
    for (const part of spreadSrc[1].split(",")) {
      const [k, v] = part.split(":").map((s) => s && s.trim().replace(/^["']|["']$/g, ""));
      if (k && v) spreads.S[camel(k)] = v;
    }
  }
  // The defaults the <svg> in Icon() carries apply to every icon.
  const icon = functionComponents(source).find((c) => c.name === "Icon");
  const root = parseSvg(icon.body).root;
  const rootAttrs = resolveAttrs(root, { ns: "icon", tokens: {}, spreads, evaluate: null, variantStops: null }, "<svg>");
  const meta = {
    viewBox: rootAttrs.viewBox ?? "0 0 24 24",
    strokeWidth: rootAttrs.strokeWidth ?? null,
    strokeLinecap: rootAttrs.strokeLinecap ?? null,
    strokeLinejoin: rootAttrs.strokeLinejoin ?? null,
    rootClassName: "ico",
  };

  const start = source.indexOf("const PATHS");
  const region = source.slice(start, source.indexOf("\n};", start));
  const out = [];
  const re = /^\s{2}(?:"([^"]+)"|([A-Za-z0-9_-]+))\s*:\s*([\s\S]*?),\s*$/gm;
  let m;
  while ((m = re.exec(region))) {
    const name = m[1] ?? m[2];
    const nodes = parseChildren(m[3]);
    const elements = [];
    flatten(nodes, { ns: "icon", paint: {}, transform: [], classes: [], tokens: {}, spreads, evaluate: null, variantStops: null }, elements);
    if (!elements.length) throw new Error(`icon "${name}" produced no elements`);
    out.push([`icon.${name}`, { ...meta }, elements]);
  }
  return out;
}

/** One group per SVG-bearing component in a file. */
function componentGroups(file, prefix, { arrow = false } = {}) {
  const source = read(file);
  const bodies = [...functionComponents(source), ...(arrow ? arrowComponents(source) : [])];
  const out = [];
  for (const { name, body } of bodies) {
    const svg = parseSvg(body);
    if (!svg) continue;
    const ns = prefix;
    const tokens = variantTokens(body);
    const ctx = {
      ns,
      paint: {},
      transform: [],
      classes: [],
      tokens,
      spreads: {},
      evaluate: localEvaluator(body),
      variantStops: variantStops(body),
    };
    const rootAttrs = resolveAttrs(svg.root, ctx, "<svg>");
    const { gradients, clips } = parseDefs(svg.children, ctx);
    const elements = [];
    flatten(svg.children, ctx, elements);
    if (!elements.length && !gradients.length) continue;
    out.push([
      `${prefix}.${name}`,
      {
        viewBox: rootAttrs.viewBox ?? null,
        rootClassName: rootAttrs.className ?? null,
        fill: rootAttrs.fill ?? null,
        stroke: rootAttrs.stroke ?? null,
        strokeWidth: rootAttrs.strokeWidth ?? null,
        strokeLinecap: rootAttrs.strokeLinecap ?? null,
        strokeLinejoin: rootAttrs.strokeLinejoin ?? null,
        gradients,
        clips,
        tokens: Object.fromEntries(Object.entries(tokens).flatMap(([k, v]) => Object.entries(v).map(([variant, color]) => [`${k}.${variant}`, color]))),
      },
      elements,
    ]);
  }
  return out;
}

/** Chains.tsx keeps its tile in an SVG data-URI template literal — parse that string directly. */
function chainGroups() {
  const source = read("src/components/hub/Chains.tsx");
  const from = source.indexOf("<svg");
  const to = source.indexOf("</svg>", from);
  if (from < 0 || to < 0) throw new Error("Chains.tsx: no SVG tile found");
  const svg = parseSvg(source.slice(from, to + 6));
  const ctx = { ns: "chain", paint: {}, transform: [], classes: [], tokens: {}, spreads: {}, evaluate: null, variantStops: null };
  const rootAttrs = resolveAttrs(svg.root, ctx, "<svg>");
  const { gradients, clips } = parseDefs(svg.children, ctx);
  const elements = [];
  flatten(svg.children, ctx, elements);
  return [[
    "chain.tile",
    {
      viewBox: rootAttrs.viewBox,
      width: rootAttrs.width ?? null,
      height: rootAttrs.height ?? null,
      gradients,
      clips,
      tokens: {},
    },
    elements,
  ]];
}

/* ------------------------------------------------------------- emitting */

const NUMERIC = new Set(["cx", "cy", "r", "rx", "ry", "x", "y", "x1", "y1", "x2", "y2", "width", "height"]);
const num = (v) => `${Number(v)}f`;
const kstr = (v) => `"${String(v).replace(/\\/g, "\\\\").replace(/"/g, '\\"').replace(/\$/g, "\\$")}"`;

function emitElement(el, indent = "            ") {
  const parts = [`kind = ${kstr(el.kind)}`];
  for (const [k, v] of Object.entries(el)) {
    if (k === "kind") continue;
    parts.push(NUMERIC.has(k) ? `${k} = ${num(v)}` : `${k} = ${kstr(v)}`);
  }
  return `${indent}SvgElement(${parts.join(", ")}),`;
}

function emitGradient(g) {
  const parts = [`id = ${kstr(g.id)}`, `kind = ${kstr(g.kind)}`];
  for (const k of ["x1", "y1", "x2", "y2", "cx", "cy", "r"]) if (g[k] !== null && g[k] !== undefined) parts.push(`${k} = ${num(g[k])}`);
  if (g.variant) parts.push(`variant = ${kstr(g.variant)}`);
  parts.push(`stops = listOf(\n${g.stops.map((s) => `                SvgStop(offset = ${num(s.offset)}, color = ${kstr(s.color)}, opacity = ${num(s.opacity)}),`).join("\n")}\n            )`);
  return `            SvgGradient(${parts.join(", ")}),`;
}

function emitGroup([name, meta, elements]) {
  const settings = [`name = ${kstr(name)}`];
  if (meta.viewBox) settings.push(`viewBox = ${kstr(meta.viewBox)}`);
  if (meta.rootClassName) settings.push(`rootClassName = ${kstr(meta.rootClassName)}`);
  if (meta.width) settings.push(`width = ${num(meta.width)}`);
  if (meta.height) settings.push(`height = ${num(meta.height)}`);
  if (meta.strokeWidth) settings.push(`strokeWidth = ${num(meta.strokeWidth)}`);
  if (meta.strokeLinecap) settings.push(`strokeLinecap = ${kstr(meta.strokeLinecap)}`);
  if (meta.strokeLinejoin) settings.push(`strokeLinejoin = ${kstr(meta.strokeLinejoin)}`);
  if (meta.fill) settings.push(`fill = ${kstr(meta.fill)}`);
  if (meta.stroke) settings.push(`stroke = ${kstr(meta.stroke)}`);
  if (meta.gradients?.length) settings.push(`gradients = listOf(\n${meta.gradients.map(emitGradient).join("\n")}\n        )`);
  if (meta.clips?.length) {
    settings.push(`clips = listOf(\n${meta.clips.map((c) => `            SvgClip(id = ${kstr(c.id)}, elements = listOf(\n${c.elements.map((e) => emitElement(e, "                ")).join("\n")}\n            )),`).join("\n")}\n        )`);
  }
  if (meta.tokens && Object.keys(meta.tokens).length) {
    settings.push(`tokens = mapOf(\n${Object.entries(meta.tokens).map(([k, v]) => `            ${kstr(k)} to ${kstr(v)},`).join("\n")}\n        )`);
  }
  return `    SvgGroup(\n        ${settings.join(",\n        ")},\n        elements = listOf(\n${elements.map((e) => emitElement(e)).join("\n")}\n        ),\n    ),`;
}

/** Everything the extractor finds — reused by the path-sampling vector builder. */
export function extractAll() {
  const groups = [
    ...iconGroups(),
    ...componentGroups("src/components/hub/Glyphs.tsx", "glyph"),
    ...componentGroups("src/components/hub/Wireframe.tsx", "wire"),
    ...componentGroups("src/components/hub/TopBar.tsx", "top"),
    ...componentGroups("src/components/ui/Art.tsx", "art", { arrow: true }),
    ...componentGroups("src/components/MascotFace.tsx", "mascot"),
    ...chainGroups(),
  ];
  groups.sort((a, b) => a[0].localeCompare(b[0]));
  return groups;
}

